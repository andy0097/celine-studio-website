/**
 * Draws the Celine Studio logos as SVG outlines from the Rizoma font file and
 * writes them to logos.generated.ts (read by the Style guide tool).
 *
 * The logos are the type styles set in Rizoma, so they are generated, never drawn
 * by hand: `type-wordmark` ("Celine", the footer) and `type-nav-logo` (CELINE /
 * STUDIO on two lines, the navbar). Re-run it when the licensed font replaces
 * the trial file (plan 7.1), changing FONT below:
 *
 *   npm i --no-save opentype.js@1.3.4
 *   node src/sanity/tools/style-guide/generate-logos.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../../..");
const tokens = JSON.parse(readFileSync(join(root, "design-system/tokens.json"), "utf8"));
const FONT = tokens.type.fonts[0].file; // fonts/rizoma/…otf, under public/
const font = opentype.loadSync(join(root, "public", FONT));
const styles = Object.fromEntries(tokens.type.groups.flatMap((g) => g.styles).map((s) => [s.name, s]));

const SIZE = 100; // drawn at 100 units per em; the SVG viewBox scales it
const em = (v) => parseFloat(v); // "-0.03em" -> -0.03
const round = (n) => Math.round(n * 100) / 100;

/** Lines of text set in the font with the type style's tracking and leading. */
function draw(lines, style) {
  const tracking = em(style.letterSpacing);
  const leading = style.lineHeight * SIZE;
  const paths = lines.map((text, i) => {
    const p = font.getPath(text, 0, i * leading, SIZE, { kerning: true, letterSpacing: tracking });
    return p;
  });
  const boxes = paths.map((p) => p.getBoundingBox());
  const x1 = Math.min(...boxes.map((b) => b.x1));
  const y1 = Math.min(...boxes.map((b) => b.y1));
  const x2 = Math.max(...boxes.map((b) => b.x2));
  const y2 = Math.max(...boxes.map((b) => b.y2));
  const d = paths.map((p) => p.toPathData(2)).join(" ");
  return { d, viewBox: [round(x1), round(y1), round(x2 - x1), round(y2 - y1)].join(" ") };
}

const logos = {
  wordmark: { name: "Wordmark", text: "Celine", style: "type-wordmark", ...draw(["Celine"], styles["type-wordmark"]) },
  stacked: { name: "Navbar logo", text: "CELINE / STUDIO", style: "type-nav-logo", ...draw(["CELINE", "STUDIO"], styles["type-nav-logo"]) },
};

const out = `// Generated by generate-logos.mjs from ${FONT}. Do not edit by hand.
export const LOGO_SOURCE_FONT = ${JSON.stringify(FONT)};

export const LOGO_PATHS = ${JSON.stringify(logos, null, 2)} as const;
`;
writeFileSync(join(here, "logos.generated.ts"), out);
console.log("logos.generated.ts:", Object.values(logos).map((l) => `${l.name} ${l.viewBox}`).join(", "));
